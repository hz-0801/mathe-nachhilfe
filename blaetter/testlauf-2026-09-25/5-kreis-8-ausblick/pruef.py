import sys
from decimal import Decimal, ROUND_HALF_UP
from sympy import pi, sqrt, Rational as R, N, nsimplify

def rund(expr, dec):
    v = Decimal(str(N(expr, 40)))
    q = Decimal(1).scaleb(-dec)
    return v.quantize(q, rounding=ROUND_HALF_UP)

def vergleiche(nr, expr, blatt):
    if '/' in blatt:
        z, n = blatt.split('/')
        b = R(int(z), int(n))
        s = nsimplify(expr)
        return nr, str(s), blatt, s == b
    dec = len(blatt.split(',')[1]) if ',' in blatt else 0
    s = rund(expr, dec)
    b = Decimal(blatt.replace(',', '.'))
    return nr, str(s).replace('.', ','), blatt, s == b

