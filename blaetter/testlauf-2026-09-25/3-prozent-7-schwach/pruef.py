# Lösungsquelltext <datei>_l.tex abgeschrieben), OK/ABWEICHUNG. Letzte Zeile: Zahl der Abweichungen.
import sys
from fractions import Fraction as F

def zahl(s):
    """Blattwert als Zeichenkette ('83,0', '3/20') -> (Wert, Nachkommastellen)."""
    s = s.strip().replace(' ', '')
    if '/' in s:
        a, b = s.split('/')
        return F(int(a), int(b)), None
    d = len(s.split(',')[1]) if ',' in s else 0
    return F(s.replace(',', '.')), d

def vergleich(nr, skript, blatt):
    wert, d = zahl(blatt)
    skript = F(skript)
    if d is None:
        ok = (skript == wert)
    else:
        # Rundung ist keine Abweichung: Skriptwert auf die Stellen des Blattwerts runden
        q = F(1, 10**d)
        gerundet = (skript / q + F(1, 2)).__floor__() * q
        ok = (gerundet == wert)
    s_txt = f"{float(skript):.6g}" if skript.denominator != 1 else str(skript.numerator)
    return f"{nr:6s} Skript {s_txt:>12s}   Blatt {blatt:>10s}   {'OK' if ok else 'ABWEICHUNG'}", ok

def ps(teil, ganzes):          # Prozentsatz in %
    return F(teil) / F(ganzes) * 100

def pw(p, g):                  # Prozentwert
    return F(p) / 100 * F(g)

def gw(w, p):                  # Grundwert
    return F(w) * 100 / F(p)

