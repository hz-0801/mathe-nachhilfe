# pruef.py – rechnet die Lösungen je Einheit unabhängig nach und vergleicht mit den Blattwerten
# Aufruf: python pruef.py zone | e1 | e2 | e3 | e4   → schreibt pruef_out_<teil>.txt
import sys
from fractions import Fraction as F
from decimal import Decimal, ROUND_HALF_UP

def rund(x, stellen=1):
    q = Decimal(1).scaleb(-stellen)
    return float(Decimal(str(float(x))).quantize(q, rounding=ROUND_HALF_UP))

def pct(teil, ganz):            # Prozentsatz in %
    return F(teil) / F(ganz) * 100

def pw(p, g):                   # Prozentwert
    return F(p) / 100 * F(g)

def gw(w, p):                   # Grundwert
    return F(w) * 100 / F(p)

