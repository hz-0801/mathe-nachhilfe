TEILE = {"zone": zone, "e1": e1, "e2": e2, "e3": e3, "e4": e4}

def main():
    teil = sys.argv[1]
    E = TEILE[teil]()
    zeilen, abw = [], 0
    for nr, s, b in E:
        ok = abs(float(s) - float(b)) < 1e-9
        if not ok:
            abw += 1
        zeilen.append(f"{nr:6} Skript {float(s):.6g}  Blatt {b}  {'OK' if ok else 'ABWEICHUNG'}")
    zeilen.append(f"Abweichungen: {abw}")
    txt = "\n".join(zeilen)
    open(f"pruef_out_{teil}.txt", "w", encoding="utf-8").write(txt + "\n")
    print(txt)

if __name__ == "__main__":
    main()
