def v(s):
    """Blattwert (Dezimalkomma) -> (float, Nachkommastellen)."""
    s = s.replace(" ", "").replace("−", "-")
    d = len(s.split(",")[1]) if "," in s else 0
    return float(s.replace(",", ".")), d

def pot(a, b, n):
    return R(a) * R(b) ** n

