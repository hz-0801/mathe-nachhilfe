def sonder(einheit):
    """Prüfungen, die kein einzelner Zahlenwert sind."""
    out = []
    if einheit == "zone":
        # 4: kleinste angebotene Einteilung e mit e * Kästchen >= Maximalwert
        for nr, maxw, k, opts, blatt in [("4a", 40, 8, [1, 5, 10], 5), ("4b", 900, 10, [50, 100, 200], 100),
                                          ("4c", 2000, 10, [100, 200, 500], 200), ("4d", R(7, 2), 7, [R(1, 2), 1, 2], R(1, 2))]:
            best = min(e for e in opts if e * k >= maxw)
            out.append((nr + "-wahl", best, blatt))
        # 1f: früh gerundet ergibt anderen Wert (Fallstrick besteht)
